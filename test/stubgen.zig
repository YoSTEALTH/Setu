//! Prints `setu_classes.pyi`, the type stubs for the test extension `setu_classes`, built at
//! comptime by `setu.stub` (never calls Python, so it needs no libpython).

const std = @import("std");
const setu = @import("setu");
const classes = @import("classes.zig");
const functions = @import("functions.zig");

/// Setu settings, read by `setu.Class` from the root file.
pub const setu_options = classes.setu_options;

const header =
    \\# Type stubs for `setu_classes`, generated by `zig build develop` (`test/stubgen.zig`).
    \\
    \\from collections.abc import Buffer, Generator, Iterator, Sequence
    \\from types import GenericAlias
    \\from typing import Any, ClassVar, Never, NoReturn, Self, disjoint_base, final
    \\
;

/// The whole `.pyi`.
const text = blk: {
    @setEvalBranchQuota(100_000_000);
    var out: []const u8 = header ++ setu.stub.constants(functions);
    for (classes.classes) |C| out = out ++ setu.stub.class(C);
    out = out ++ setu.stub.functions(functions, @embedFile("functions.zig"));
    break :blk setu.stub.format(out);
};

/// Writes `text` to stdout.
pub fn main() void {
    var rest: []const u8 = text;
    while (rest.len > 0) {
        const n = std.os.linux.write(1, rest.ptr, rest.len);
        if (@as(isize, @bitCast(n)) <= 0) std.process.exit(1);
        rest = rest[n..];
    }
}
